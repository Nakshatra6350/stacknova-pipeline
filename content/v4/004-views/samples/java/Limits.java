import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.atomic.AtomicLong;

/** The cases that need Postgres: what the database does at the limit. */
final class Limits {
    static final int N = 1000;
    static final String INT_MAX = "2147483647";

    /** A fresh table whose id sequence has just handed out its last value. */
    static void atTheLimit(Connection c) throws SQLException {
        Db.run(c,
            "DROP TABLE IF EXISTS comments, videos CASCADE",
            "CREATE TABLE videos (id SERIAL PRIMARY KEY, title TEXT NOT NULL,"
                + " views BIGINT NOT NULL DEFAULT 0)",
            "SELECT setval('videos_id_seq', " + INT_MAX + ")");
    }

    /** 1,000 inserts: how many does the database refuse, and why? */
    static int tryInserts(Connection c, String label) throws SQLException {
        int refused = 0;
        String message = "";
        String sql = "INSERT INTO videos (title) VALUES ('new')";
        try (PreparedStatement p = c.prepareStatement(sql)) {
            for (int i = 0; i < N; i++) {
                try {
                    p.executeUpdate();
                } catch (SQLException e) {
                    refused++;
                    message = e.getSQLState() + " " + e.getMessage();
                }
            }
        }
        System.out.println(label + ": " + refused + " of " + N + " refused"
            + (refused > 0 ? "\n  " + message : ""));
        return refused;
    }

    /** Java goes negative in silence. A SQL INTEGER refuses out loud. */
    static void counterSql(Connection c) throws SQLException {
        for (String type : new String[] {"INTEGER", "BIGINT"}) {
            Db.run(c, "DROP TABLE IF EXISTS tally",
                "CREATE TABLE tally (id INT PRIMARY KEY, views " + type + ")",
                "INSERT INTO tally VALUES (1, " + INT_MAX + ")");
            int refused = 0;
            String message = "";
            String sql = "UPDATE tally SET views = views + 1 WHERE id = 1";
            try (PreparedStatement p = c.prepareStatement(sql)) {
                for (int i = 0; i < N; i++) {
                    try {
                        p.executeUpdate();
                    } catch (SQLException e) {
                        refused++;
                        message = e.getSQLState() + " " + e.getMessage();
                    }
                }
            }
            System.out.println(type + ": " + refused + " of " + N
                + " refused, views now "
                + Db.one(c, "SELECT views FROM tally") + " " + message);
        }
    }

    /** The sequence is out of values: no insert can succeed. */
    static void outOfIds(Connection c) throws SQLException {
        atTheLimit(c);
        tryInserts(c, "SERIAL at the limit");
    }

    /** The fix most of us write first, and why it isn't one. */
    static void alterOnly(Connection c) throws SQLException {
        atTheLimit(c);
        Db.run(c, "ALTER TABLE videos ALTER COLUMN id TYPE BIGINT");
        System.out.println("column is now  " + columnType(c, "videos", "id"));
        System.out.println("sequence is    " + sequenceType(c)
            + ", its limit " + sequenceMax(c));
        tryInserts(c, "column BIGINT, sequence untouched");

        Db.run(c, "ALTER SEQUENCE videos_id_seq AS BIGINT");
        System.out.println("sequence is    " + sequenceType(c)
            + ", its limit " + sequenceMax(c));
        tryInserts(c, "column BIGINT, sequence BIGINT");
        System.out.println("largest id now "
            + Db.one(c, "SELECT max(id) FROM videos"));
    }

    /** An identity column, for comparison with SERIAL. */
    static void identity(Connection c) throws SQLException {
        Db.run(c, "DROP TABLE IF EXISTS comments, videos CASCADE",
            "CREATE TABLE videos (id INT GENERATED BY DEFAULT AS IDENTITY"
                + " PRIMARY KEY, title TEXT NOT NULL,"
                + " views BIGINT NOT NULL DEFAULT 0)",
            "SELECT setval('videos_id_seq', " + INT_MAX + ")");
        tryInserts(c, "IDENTITY at the limit");
        Db.run(c, "ALTER TABLE videos ALTER COLUMN id TYPE BIGINT");
        System.out.println("column is now  " + columnType(c, "videos", "id"));
        System.out.println("sequence is    " + sequenceType(c)
            + ", its limit " + sequenceMax(c));
        tryInserts(c, "IDENTITY after ALTER COLUMN");
    }

    /** videos.id is safe, but a table pointing at it still holds an int. */
    static void fkLeft(Connection c) throws SQLException {
        for (String type : new String[] {"INTEGER", "BIGINT"}) {
            atTheLimit(c);
            Db.run(c, "ALTER TABLE videos ALTER COLUMN id TYPE BIGINT",
                "ALTER SEQUENCE videos_id_seq AS BIGINT",
                "CREATE TABLE comments (id BIGSERIAL PRIMARY KEY, video_id "
                    + type + " NOT NULL REFERENCES videos (id), body TEXT)",
                "INSERT INTO videos (title) VALUES ('past the limit')");
            long video = Db.one(c, "SELECT max(id) FROM videos");
            int refused = 0;
            String message = "";
            String sql = "INSERT INTO comments (video_id, body)"
                + " VALUES (?, 'nice')";
            try (PreparedStatement p = c.prepareStatement(sql)) {
                for (int i = 0; i < N; i++) {
                    p.setLong(1, video);
                    try {
                        p.executeUpdate();
                    } catch (SQLException e) {
                        refused++;
                        message = e.getSQLState() + " " + e.getMessage();
                    }
                }
            }
            System.out.println("comments.video_id " + type + ": " + refused
                + " of " + N + " refused " + message);
        }
    }

    /** IDs run out faster than rows: a failed insert still uses one up. */
    static void burn(Connection c) throws SQLException {
        Db.run(c, "DROP TABLE IF EXISTS tags",
            "CREATE TABLE tags (id SERIAL PRIMARY KEY,"
                + " name TEXT NOT NULL UNIQUE)",
            "INSERT INTO tags (name) VALUES ('go')");

        long before = lastId(c);
        String upsert = "INSERT INTO tags (name) VALUES ('go')"
            + " ON CONFLICT (name) DO NOTHING";
        for (int i = 0; i < N; i++) Db.run(c, upsert);
        System.out.println("ON CONFLICT DO NOTHING: rows "
            + Db.one(c, "SELECT count(*) FROM tags") + ", ids used "
            + (lastId(c) - before));

        before = lastId(c);
        c.setAutoCommit(false);
        for (int i = 0; i < N; i++) {
            Db.run(c, "INSERT INTO tags (name) VALUES ('t" + i + "')");
            c.rollback();
        }
        c.setAutoCommit(true);
        System.out.println("rolled-back inserts:    rows "
            + Db.one(c, "SELECT count(*) FROM tags") + ", ids used "
            + (lastId(c) - before));

        before = lastId(c);
        String careful = "INSERT INTO tags (name) SELECT 'go' WHERE NOT EXISTS"
            + " (SELECT 1 FROM tags WHERE name = 'go')";
        for (int i = 0; i < N; i++) Db.run(c, careful);
        System.out.println("look first, then insert: rows "
            + Db.one(c, "SELECT count(*) FROM tags") + ", ids used "
            + (lastId(c) - before));
    }

    static long lastId(Connection c) throws SQLException {
        return Db.one(c, "SELECT last_value FROM tags_id_seq");
    }

    /** The column holds 3 billion. How does Java read it? */
    static void readInt(Connection c) throws SQLException {
        Db.run(c, "DROP TABLE IF EXISTS tally",
            "CREATE TABLE tally (id INT PRIMARY KEY, views BIGINT)",
            "INSERT INTO tally SELECT g, 3000000000 + g"
                + " FROM generate_series(1, " + N + ") g");
        int thrown = 0;
        int silent = 0;
        int wrongLong = 0;
        String message = "";
        try (Statement s = c.createStatement();
             ResultSet r = s.executeQuery("SELECT id, views FROM tally")) {
            while (r.next()) {
                long truth = 3_000_000_000L + r.getInt(1);
                try {
                    r.getInt(2);
                } catch (SQLException e) {
                    thrown++;
                    message = e.getMessage();
                }
                int cast = (int) r.getLong(2);
                if (cast != truth) silent++;
                if (r.getLong(2) != truth) wrongLong++;
            }
        }
        System.out.println("rs.getInt         " + thrown + " of " + N
            + " threw: " + message);
        System.out.println("(int) rs.getLong  " + silent + " of " + N
            + " silently wrong");
        System.out.println("rs.getLong        " + wrongLong + " of " + N
            + " wrong");
    }

    /** Every column fed by a sequence, and how much of its room is gone. */
    static final String RUNWAY = """
        SELECT c.table_name, c.column_name, c.data_type,
               s.data_type::text AS seq_type, s.last_value,
               round(100.0 * s.last_value / least(s.max_value,
                 CASE c.data_type WHEN 'integer' THEN 2147483647
                      ELSE 9223372036854775807 END), 1) AS used_pct
        FROM information_schema.columns c
        JOIN pg_sequences s
          ON pg_get_serial_sequence(
               quote_ident(c.table_schema) || '.'
               || quote_ident(c.table_name), c.column_name)
             = quote_ident(s.schemaname) || '.'
               || quote_ident(s.sequencename)
        WHERE c.table_schema NOT IN ('pg_catalog', 'information_schema')
        ORDER BY used_pct DESC NULLS LAST""";

    /** Foreign keys narrower than the column they point at. */
    static final String NARROW_FKS = """
        SELECT con.conrelid::regclass::text AS table_name,
               a.attname AS column_name,
               format_type(a.atttypid, a.atttypmod) AS column_type,
               format_type(b.atttypid, b.atttypmod) AS points_at
        FROM pg_constraint con
        JOIN pg_attribute a ON a.attrelid = con.conrelid
             AND a.attnum = con.conkey[1]
        JOIN pg_attribute b ON b.attrelid = con.confrelid
             AND b.attnum = con.confkey[1]
        WHERE con.contype = 'f' AND a.atttypid <> b.atttypid""";

    /** Five tables at known levels: does the check find the right ones? */
    static void runway(Connection c) throws SQLException {
        Db.run(c, "DROP TABLE IF EXISTS comments, videos, tags, tally,"
                + " view_shards CASCADE",
            "DROP SCHEMA IF EXISTS watch CASCADE", "CREATE SCHEMA watch",
            "CREATE TABLE watch.healthy (id SERIAL PRIMARY KEY)",
            "SELECT setval('watch.healthy_id_seq', 214748364)",
            "CREATE TABLE watch.getting_close (id SERIAL PRIMARY KEY)",
            "SELECT setval('watch.getting_close_id_seq', 1546188226)",
            "CREATE TABLE watch.nearly_out (id SERIAL PRIMARY KEY)",
            "SELECT setval('watch.nearly_out_id_seq', 2145336164)",
            "CREATE TABLE watch.big_column (id SERIAL PRIMARY KEY)",
            "ALTER TABLE watch.big_column ALTER COLUMN id TYPE BIGINT",
            "SELECT setval('watch.big_column_id_seq', 2125000000)",
            "CREATE TABLE watch.big_seq (id SERIAL PRIMARY KEY)",
            "ALTER SEQUENCE watch.big_seq_id_seq AS BIGINT",
            "SELECT setval('watch.big_seq_id_seq', 2125000000)",
            "CREATE TABLE watch.fine (id BIGSERIAL PRIMARY KEY)",
            "SELECT setval('watch.fine_id_seq', 2125000000)",
            "CREATE TABLE watch.child (id BIGSERIAL PRIMARY KEY,"
                + " parent INTEGER REFERENCES watch.fine (id))");
        print(c, RUNWAY + " ");
        print(c, NARROW_FKS);
        Db.run(c, "DROP SCHEMA watch CASCADE");
    }

    static void print(Connection c, String sql) throws SQLException {
        try (Statement s = c.createStatement();
             ResultSet r = s.executeQuery(sql)) {
            int columns = r.getMetaData().getColumnCount();
            while (r.next()) {
                StringBuilder row = new StringBuilder();
                for (int i = 1; i <= columns; i++) {
                    row.append(String.format("%-15s", r.getString(i)));
                }
                System.out.println(row.toString().stripTrailing());
            }
        }
    }

    /** One row for every view, against several rows or a batch. */
    static void hotRow(Connection c) throws Exception {
        int threads = 8;
        int each = 2000;
        long expected = (long) threads * each;

        Db.run(c, "DROP TABLE IF EXISTS tally, view_shards",
            "CREATE TABLE tally (id INT PRIMARY KEY, views BIGINT NOT NULL)",
            "INSERT INTO tally VALUES (1, 0)",
            "CREATE TABLE view_shards (video_id BIGINT, shard INT,"
                + " n BIGINT NOT NULL, PRIMARY KEY (video_id, shard))");

        long took = workers(threads, (me, db) -> {
            String sql = "UPDATE tally SET views = views + 1 WHERE id = 1";
            try (PreparedStatement p = db.prepareStatement(sql)) {
                for (int i = 0; i < each; i++) p.executeUpdate();
            }
        });
        System.out.println("one row    " + took + " ms, counted "
            + Db.one(c, "SELECT views FROM tally") + " of " + expected);

        took = workers(threads, (me, db) -> {
            String sql = "INSERT INTO view_shards VALUES (1, ?, 1)"
                + " ON CONFLICT (video_id, shard)"
                + " DO UPDATE SET n = view_shards.n + 1";
            try (PreparedStatement p = db.prepareStatement(sql)) {
                for (int i = 0; i < each; i++) {
                    p.setInt(1, (me * 4 + i % 4) % 32);
                    p.executeUpdate();
                }
            }
        });
        System.out.println("32 shards  " + took + " ms, counted "
            + Db.one(c, "SELECT sum(n) FROM view_shards") + " of " + expected);

        Db.run(c, "UPDATE tally SET views = 0");
        AtomicLong pending = new AtomicLong();
        AtomicLong writes = new AtomicLong();
        Thread[] done = new Thread[1];
        long start = System.nanoTime();
        List<Thread> viewers = new ArrayList<>();
        for (int t = 0; t < threads; t++) {
            Thread v = new Thread(() -> {
                for (int i = 0; i < each * 100; i++) pending.incrementAndGet();
            });
            viewers.add(v);
            v.start();
        }
        done[0] = new Thread(() -> {
            try (Connection db = Db.open();
                 PreparedStatement p = db.prepareStatement(
                     "UPDATE tally SET views = views + ? WHERE id = 1")) {
                boolean alive = true;
                while (alive) {
                    alive = viewers.stream().anyMatch(Thread::isAlive);
                    long batch = pending.getAndSet(0);
                    if (batch > 0) {
                        p.setLong(1, batch);
                        p.executeUpdate();
                        writes.incrementAndGet();
                    }
                    Thread.sleep(10);
                }
            } catch (Exception e) {
                throw new IllegalStateException(e);
            }
        });
        done[0].start();
        for (Thread v : viewers) v.join();
        done[0].join();
        long ms = (System.nanoTime() - start) / 1_000_000;
        System.out.println("batched    " + ms + " ms, counted "
            + Db.one(c, "SELECT views FROM tally") + " of "
            + expected * 100 + " in " + writes.get() + " writes");
    }

    interface Work {
        void run(int me, Connection db) throws SQLException;
    }

    static long workers(int threads, Work work) throws Exception {
        List<Thread> all = new ArrayList<>();
        long start = System.nanoTime();
        for (int t = 0; t < threads; t++) {
            int me = t;
            Thread thread = new Thread(() -> {
                try (Connection db = Db.open()) {
                    work.run(me, db);
                } catch (SQLException e) {
                    throw new IllegalStateException(e);
                }
            });
            all.add(thread);
            thread.start();
        }
        for (Thread t : all) t.join();
        return (System.nanoTime() - start) / 1_000_000;
    }

    static String columnType(Connection c, String table, String column)
        throws SQLException {
        return Db.text(c, "SELECT data_type FROM information_schema.columns"
            + " WHERE table_name = '" + table + "' AND column_name = '"
            + column + "'");
    }

    static String sequenceType(Connection c) throws SQLException {
        return Db.text(c, "SELECT data_type::text FROM pg_sequences"
            + " WHERE sequencename = 'videos_id_seq'");
    }

    static long sequenceMax(Connection c) throws SQLException {
        return Db.one(c, "SELECT max_value FROM pg_sequences"
            + " WHERE sequencename = 'videos_id_seq'");
    }

    /** Already out of IDs on a live INTEGER column: buy time, then migrate. */
    static void onFire(Connection c) throws SQLException {
        atTheLimit(c);
        tryInserts(c, "before");
        Db.run(c, "ALTER SEQUENCE videos_id_seq MINVALUE -2147483648"
            + " MAXVALUE -1 START -1 RESTART -1 INCREMENT -1");
        tryInserts(c, "counting down from -1");
        System.out.println("column still   "
            + columnType(c, "videos", "id") + ", smallest id "
            + Db.one(c, "SELECT min(id) FROM videos"));
    }

    private Limits() {}
}
